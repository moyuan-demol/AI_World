"""对话性 / 自我介绍问题的识别（纯函数、零依赖、可离线测试）。

为什么需要它（来自用户实测）：
- 用户问「你是做什么的，介绍一下你自己」，离线检索却把公共库里的
  「问题 2：两路检索结果用什么算法融合?」当成相关片段列了出来 —— 两者只共享
  "是 / 什 / 么"这类常见字，却刚好越过了 0.18 的最低相关性阈值，形成"假命中"；
- 用户期望的正确行为是：**先检索知识库；若没有达到更高门槛的关联片段，就不要
  列出任何知识库片段**，而是给出正确的角色自我介绍。

设计边界（保持简单、可测，且不误伤领域问题）：
- 只认少量典型句式，不引入语义模型，因此行为确定、可离线断言；
- "某某药物的作用是什么"这类只共享常见字、且不含"你"的领域问题不受影响；
- "你好，请问阿司匹林怎么吃"这种"问候 + 领域问题"也不会被误判：
  纯问候集采用**整句精确匹配**，正文里还有其它内容就不算寒暄。

调用位置：ChatService.chat —— 命中时改用 settings.self_intro_min_score 这一更高的
相关性门槛来筛选检索片段（见 app/services/chat_service.py）。
"""

from __future__ import annotations

import re

# 归一化：去掉空白与常见中英文标点，再转小写，便于做子串匹配（不做分词）。
_PUNCT_RE = re.compile(r"""[\s，。！？、；：,.!?;:~～…·"'“”‘’()（）\[\]【】<>《》\-_/\\|]+""")

# 纯问候：只有"整句就是这句问候"时才成立。
# 为什么不做子串匹配：否则"你好，请问阿司匹林怎么吃"会被当成寒暄，反而丢掉领域检索。
_GREETING_ONLY = {
    "你好",
    "您好",
    "嗨",
    "哈喽",
    "hi",
    "hello",
    "在吗",
    "在么",
    "在不在",
    "你在吗",
    "有人吗",
}

# 明确的自我介绍句式（归一化后做子串匹配）。
# 为什么大量句式都带"你"：这是最强、最便宜的边界 —— 领域问题几乎不会用第二人称
# 询问系统自身，因此"某某药物的作用是什么"这类问题天然不会命中。
_SELF_INTRO_PATTERNS = (
    "你是谁",
    "你叫什么",
    "你是什么",
    "你是干什么",
    "你是做什么",
    "你做什么",
    "你干啥",
    "你是哪位",
    "你哪位",
    "介绍一下你自己",
    "介绍一下自己",
    "介绍一下你",
    "介绍下你自己",
    "介绍下自己",
    "自我介绍",
    "你能做什么",
    "你能干什么",
    "你会什么",
    "你能帮我做什么",
    "你可以做什么",
    "你有什么功能",
    "你有什么能力",
    "你有哪些功能",
)


def normalize_question(text: str) -> str:
    """纯函数：去掉空白/标点并转小写（仅供匹配，不做分词）。"""
    return _PUNCT_RE.sub("", (text or "").lower())


def is_self_intro_question(text: str) -> bool:
    """判断一句话是不是"对话性寒暄 / 自我介绍"类问题。

    真：你是谁 / 你是做什么的 / 介绍一下你自己 / 你能做什么 / 你好 / 在吗 …
    假：某某药物的作用是什么 / 这个系统的阈值是多少 / 你好，请问阿司匹林怎么吃
        / 你能帮我查一下这篇论文的作者吗 / 什么是 RRF 融合
    """
    normalized = normalize_question(text)
    if not normalized:
        return False
    if normalized in _GREETING_ONLY:
        return True
    return any(pattern in normalized for pattern in _SELF_INTRO_PATTERNS)
